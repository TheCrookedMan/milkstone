import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const colors = new Set()
async function scan(folder) {
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    if (['node_modules', 'dist', 'shadcn-catalog'].includes(entry.name)) continue
    const path = join(folder, entry.name)
    if (entry.isDirectory()) await scan(path)
    else if (/\.(css|vue)$/.test(path) && entry.name !== 'theme-colors.css') {
      const source = await readFile(path, 'utf8')
      for (const match of source.matchAll(/--milk-color-([a-f\d]{8}|[a-f\d]{6})\b/g)) colors.add(match[1])
    }
  }
}
await scan(join(root, 'src'))
await scan(join(root, 'skills/milk-white-web-design/assets'))
const inverse = hex => [0, 2, 4].map(i => (255 - parseInt(hex.slice(i, i + 2), 16)).toString(16).padStart(2, '0')).join('') + hex.slice(6)
const entries = [...colors].sort()
const rules = invert => entries.map(hex => `  --milk-color-${hex}:#${invert ? inverse(hex) : hex};`).join('\n')
await writeFile(join(root, 'skills/milk-white-web-design/assets/theme-colors.css'), `/* Generated by scripts/sync-theme-colors.mjs. RGB complements; alpha is preserved. */\n:root {\n${rules(false)}\n}\n:root[data-theme="dark"] {\n  color-scheme:dark;\n${rules(true)}\n}\n`)
console.log(`Synced ${entries.length} exact inverse theme colors.`)
